SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS cafes (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 slug VARCHAR(40) NOT NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 cafe_id INT UNSIGNED NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('owner','staff') NOT NULL DEFAULT 'owner',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_users_cafe FOREIGN KEY (cafe_id) REFERENCES cafes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS cafe_tables (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 cafe_id INT UNSIGNED NOT NULL,
 display_number INT UNSIGNED NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 UNIQUE KEY uq_cafe_table (cafe_id, display_number),
 CONSTRAINT fk_tables_cafe FOREIGN KEY (cafe_id) REFERENCES cafes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS menu_categories (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 cafe_id INT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL,
 sort_order INT NOT NULL DEFAULT 0,
 UNIQUE KEY uq_cafe_category (cafe_id, name),
 CONSTRAINT fk_categories_cafe FOREIGN KEY (cafe_id) REFERENCES cafes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS menu_items (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 cafe_id INT UNSIGNED NOT NULL,
 category_id INT UNSIGNED NULL,
 name VARCHAR(150) NOT NULL,
 description TEXT NOT NULL,
 price_paise INT UNSIGNED NOT NULL,
 available TINYINT(1) NOT NULL DEFAULT 1,
 visible TINYINT(1) NOT NULL DEFAULT 1,
 image_path VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_items_cafe (cafe_id),
 CONSTRAINT fk_items_cafe FOREIGN KEY (cafe_id) REFERENCES cafes(id) ON DELETE CASCADE,
 CONSTRAINT fk_items_category FOREIGN KEY (category_id) REFERENCES menu_categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 cafe_id INT UNSIGNED NOT NULL,
 order_number VARCHAR(40) NOT NULL UNIQUE,
 table_number INT UNSIGNED NULL,
 status ENUM('New','Accepted','Preparing','Ready','Served','Cancelled') NOT NULL DEFAULT 'New',
 instructions TEXT NOT NULL,
 total_paise INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY idx_orders_cafe_created (cafe_id, created_at),
 CONSTRAINT fk_orders_cafe FOREIGN KEY (cafe_id) REFERENCES cafes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 menu_item_id INT UNSIGNED NULL,
 item_name VARCHAR(150) NOT NULL,
 unit_price_paise INT UNSIGNED NOT NULL,
 quantity TINYINT UNSIGNED NOT NULL,
 CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
 CONSTRAINT fk_order_items_menu_item FOREIGN KEY (menu_item_id) REFERENCES menu_items(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
